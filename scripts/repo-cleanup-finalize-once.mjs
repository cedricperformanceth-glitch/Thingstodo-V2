import fs from 'node:fs';
import path from 'node:path';

const shortIds = new Set([
  'thing-lao-cooking-class-with-nyay',
  'thing-tham-chang-elephant-cave',
  'thing-tha-falang',
  'thing-pha-inh-cave',
  'thing-cool-springs-loop',
  'thing-sandstone-buddhas',
]);

const parseGenerated = (file) => {
  const source = fs.readFileSync(file, 'utf8');
  const token = 'const data = ';
  const start = source.indexOf(token);
  const end = source.indexOf(';\nexport const city', start);
  if (start < 0 || end < 0) return null;
  return JSON.parse(source.slice(start + token.length, end));
};
const writeGenerated = (file, data) => fs.writeFileSync(file, `import type { City, Place, ThingToDo } from '../../../core/models/types';\n\n// Generated by the development-only Atlas pipeline. Manual locks are retained in the source container.\nconst data = ${JSON.stringify(data, null, 2)};\nexport const city = data.city as City;\nexport const places = data.places as Place[];\nexport const things = data.things as ThingToDo[];\n`);
const stripSecondary = (things = []) => {
  for (const thing of things) {
    if (!shortIds.has(thing.id) || !thing.fieldCard) continue;
    delete thing.fieldCard.secondaryStory;
  }
};

const generatedRoot = path.join('src', 'content', 'generated', 'laos');
for (const name of fs.readdirSync(generatedRoot)) {
  if (!name.endsWith('.ts')) continue;
  const file = path.join(generatedRoot, name);
  const data = parseGenerated(file);
  if (!data) continue;
  stripSecondary(data.things);
  writeGenerated(file, data);
}

const citiesRoot = path.join('pipeline', 'cities');
for (const country of fs.readdirSync(citiesRoot)) {
  const dir = path.join(citiesRoot, country);
  if (!fs.statSync(dir).isDirectory()) continue;
  for (const name of fs.readdirSync(dir)) {
    if (!name.endsWith('.json')) continue;
    const file = path.join(dir, name);
    const draft = JSON.parse(fs.readFileSync(file, 'utf8'));
    stripSecondary(draft.things);
    fs.writeFileSync(file, `${JSON.stringify(draft, null, 2)}\n`);
  }
}

const editorial = JSON.parse(fs.readFileSync('src/content/field-card-editorial.json', 'utf8'));
for (const id of shortIds) {
  if (!editorial[id] || editorial[id].secondaryStory !== null) throw new Error(`${id}: canonical short-card marker is missing`);
}

fs.rmSync('scripts/repo-cleanup-finalize-once.mjs');
