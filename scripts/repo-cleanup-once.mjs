const root = process.cwd();
const read = (rel) => fs.readFileSync(path.join(root, rel), 'utf8');
const write = (rel, value) => fs.writeFileSync(path.join(root, rel), value);
const readJson = (rel) => JSON.parse(read(rel));
const writeJson = (rel, value) => write(rel, `${JSON.stringify(value, null, 2)}\n`);
const exists = (rel) => fs.existsSync(path.join(root, rel));
const remove = (rel) => { if (exists(rel)) fs.rmSync(path.join(root, rel), { force: true, recursive: true }); };
const listFiles = (dir, predicate = () => true) => {
  const abs = path.join(root, dir);
  if (!fs.existsSync(abs)) return [];
  return fs.readdirSync(abs, { withFileTypes: true }).flatMap((entry) => {
    const rel = path.join(dir, entry.name);
    return entry.isDirectory() ? listFiles(rel, predicate) : predicate(rel) ? [rel] : [];
  });
};
const assertReplace = (rel, before, after) => {
  const source = read(rel);
  if (!source.includes(before)) throw new Error(`Expected cleanup pattern not found in ${rel}: ${before.slice(0, 100)}`);
  write(rel, source.replace(before, after));
};

function parseGenerated(rel) {
  const source = read(rel);
  const startToken = 'const data = ';
  const start = source.indexOf(startToken);
  const end = source.indexOf(';\nexport const city', start);
  if (start < 0 || end < 0) throw new Error(`Unable to parse generated city module ${rel}`);
  return JSON.parse(source.slice(start + startToken.length, end));
}
function writeGenerated(rel, data) {
  write(rel, `import type { City, Place, ThingToDo } from '../../../core/models/types';\n\n// Generated by the development-only Atlas pipeline. Manual locks are retained in the source container.\nconst data = ${JSON.stringify(data, null, 2)};\nexport const city = data.city as City;\nexport const places = data.places as Place[];\nexport const things = data.things as ThingToDo[];\n`);
}
function stripAuditMetadata(value) {
  if (Array.isArray(value)) return value.map(stripAuditMetadata);
  if (!value || typeof value !== 'object') return value;
  const result = {};
  for (const [key, child] of Object.entries(value)) {
    if (key === 'checkedAt' || key === 'reviewedAt' || key === 'generatedAt' || key === 'publicationQa') continue;
    result[key] = stripAuditMetadata(child);
  }
  return result;
}
function slugify(value) {
  return String(value).toLowerCase().normalize('NFD').replace(/[\u0300-\u036f]/g, '').replace(/&/g, ' and ').replace(/[’']/g, '').replace(/[^a-z0-9]+/g, '-').replace(/(^-|-$)/g, '');
}
function applySwaps(places, swapsByCategory = {}) {
  for (const swaps of Object.values(swapsByCategory)) {
    for (const [firstId, secondId] of swaps) {
      const first = places.findIndex((item) => item.id === firstId);
      const second = places.findIndex((item) => item.id === secondId);
      if (first >= 0 && second >= 0) [places[first], places[second]] = [places[second], places[first]];
    }
  }
}
function findThing(data, id) { return data.things?.find((thing) => thing.id === id); }
function applyExploreOverride(data, override) {
  if (!override) return;
  data.city.exploreBoard ??= { featuredThingIds: [] };
  data.city.exploreBoard.featuredThingIds = [...override.featuredThingIds];
  for (const [id, metadata] of Object.entries(override.thingMetadata ?? {})) {
    const thing = findThing(data, id);
    if (thing) thing.exploreBoard = structuredClone(metadata);
  }
}
function applyCategoryOverrides(city, override, draft) {
  if (!override) return;
  city.categoryTargets ??= {};
  city.manualLocks ??= {};
  for (const [category, value] of Object.entries(override)) {
    city.categoryTargets[category] = value;
    const editorialPolicy = draft?.researchPlan?.categoryTargetPolicies?.[category];
    const existingLock = city.manualLocks[`categoryTargets.${category}`];
    if (editorialPolicy || existingLock) {
      city.manualLocks[`categoryTargets.${category}`] = { value, source: 'manual', locked: true };
    }
  }
}
function removeClosedPlaceLines(rel, closedIds) {
  if (!exists(rel)) return;
  const lines = read(rel).split('\n');
  const kept = lines.filter((line) => {
    const marker = line.indexOf('place(');
    if (marker < 0) return true;
    const start = marker + 'place('.length;
    const quote = line[start];
    if (!['\'', '"', '`'].includes(quote)) return true;
    let end = start + 1;
    let escaped = false;
    for (; end < line.length; end += 1) {
      const char = line[end];
      if (escaped) { escaped = false; continue; }
      if (char === '\\') { escaped = true; continue; }
      if (char === quote) break;
    }
    if (end >= line.length) return true;
    const literal = line.slice(start, end + 1);
    let name;
    try { name = Function(`"use strict"; return (${literal});`)(); } catch { return true; }
    return !closedIds.has(`place-${slugify(name)}`);
  });
  let source = kept.join('\n');
  source = source
    .replace('// Restaurants — deliberately larger than the 24-card target so ranking has real choice.', '// Restaurants — active researched candidates.')
    .replace('// Coffee — 25 genuinely identifiable current café/coffee candidates, no restaurant duplication.', '// Coffee — active researched candidates, no restaurant duplication.')
    .replace('// Accommodation — 24 candidates for a 21-card target.', '// Accommodation — active researched candidates.');
  source = source
    .replace(/,\s*checkedAt:\s*'[^']*'/g, '')
    .replace(/,\s*checkedAt:\s*"[^"]*"/g, '')
    .replace(/,\s*reviewedAt:\s*REVIEWED_AT/g, '')
    .replace(/,\s*reviewedAt:\s*'[^']*'/g, '')
    .replace(/,\s*reviewedAt:\s*"[^"]*"/g, '');
  write(rel, source);
}
function traverse(value, visitor) {
  if (Array.isArray(value)) { for (const item of value) traverse(item, visitor); return; }
  if (!value || typeof value !== 'object') return;
  visitor(value);
  for (const child of Object.values(value)) traverse(child, visitor);
}

