// 8) Sanity checks: effective category targets must match the cleaned active card inventory where a runtime override previously existed.
for (const { data } of generatedByCityId.values()) {
  const originalOverride = categoryOverrides[data.city.id];
  if (!originalOverride) continue;
  for (const [category, target] of Object.entries(originalOverride)) {
    if (category === 'things-to-do') {
      if ((data.things ?? []).length < target) throw new Error(`${data.city.slug}: ${category} target ${target} exceeds ${data.things.length} activities`);
    } else {
      const count = (data.places ?? []).filter((place) => place.category === category).length;
      if (count !== target) throw new Error(`${data.city.slug}: cleaned ${category} count ${count} does not equal canonical target ${target}`);
    }
  }
}

