import assert from 'node:assert/strict';
import { emptyDraft, setCategoryTarget, syncGenerationContract, validateCityCategories } from './lib/city-pipeline.mjs';
import { evaluateCityPublication } from './lib/city-publish-qa.mjs';

const draft = emptyDraft('laos', 'editor-categories', 'compact', 'village');
draft.cityData.categories = ['things-to-do', 'cafes', 'practical-services'];
syncGenerationContract(draft);
assert.deepEqual(draft.cityData.categories, ['things-to-do', 'cafes', 'practical-services']);
assert.deepEqual(draft.cityData.categoryTargets, {});
assert.equal(draft.researchPlan.selection.categories.restaurants, undefined);
assert.ok(draft.researchPlan.selection.categories['things-to-do']);
assert.ok(draft.researchPlan.selection.categories.cafes);
assert.ok(draft.researchPlan.selection.categories['practical-services']);
setCategoryTarget(draft, 'things-to-do', 2);
setCategoryTarget(draft, 'cafes', 1);
syncGenerationContract(draft);
assert.deepEqual(draft.cityData.categoryTargets, { 'things-to-do': 2, cafes: 1 }, 'Admin counts must be preserved exactly without global ranges.');
assert.throws(() => validateCityCategories(['things-to-do', 'gyms'], 'village', 'laos/test'), /not allowed/);
assert.throws(() => validateCityCategories(['cafes'], 'village', 'laos/test'), /must include things-to-do/);
assert.throws(() => validateCityCategories(['things-to-do', 'cafes', 'cafes'], 'village', 'laos/test'), /must be unique/);
const qaDraft = structuredClone(draft);
qaDraft.city = 'editor-categories';
qaDraft.things = [];
qaDraft.places = [];
const qa = evaluateCityPublication(qaDraft);
assert.equal(qa.errors.some((entry) => /target/.test(entry.code)), false, 'Publication QA must never reject a city because its actual counts differ from admin counts.');
console.log('City.categories and admin count authority tests passed.');
